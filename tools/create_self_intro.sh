## 2 分钟标准版

您好，我叫 XXX，是 XXX 大学软件工程专业 2027 届毕业生，今年 6 月开始在 XXX 公司实习，岗位是软件测试实习生。

实习期间我主要做两件事：一是接口自动化测试，二是手工功能测试。

接口自动化方面，我用 Python + pytest + requests + Allure 搭建了 HSC 系统管理模块的自动化测试框架。框架采用 config.py → base.py → utils_*.py → test_*.py 的分层结构，用 YAML 做数据驱动，用 fixture 实现测试数据自动清理，集成 Allure 生成测试报告。目前覆盖了 5 个模块，100 多条接口用例。

手工测试方面，我参与过平台设置页、角色管理等模块的回归测试，累计产出 60 多条手工测试用例，发现并跟踪了多个功能缺陷。

我考了软件评测师证书，对测试理论和用例设计方法比较熟悉。希望应聘贵公司的测试开发岗位，继续提升自动化测试和 CI/CD 方面的能力。

