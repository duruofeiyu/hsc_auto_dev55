## 3 分钟详细版

您好，我叫 XXX，来自 XXX 大学软件工程专业，2027 年毕业。今年 6 月开始在 XXX 公司担任软件测试实习生，至今已有 2 个多月。

我的实习工作可以分为三个部分：

**第一部分是接口自动化测试。** 我使用 Python + pytest + requests + Allure 为 HSC 医院安全驾驶舱系统搭建了接口自动化测试框架。项目采用 config.py 配置层、base.py 工具层、utils_*.py 接口层、test_*.py 用例层的分层结构。使用 YAML 管理测试数据，实现数据驱动；使用 fixture 的 yield 模式自动创建和清理测试数据；使用 Allure 生成可视化测试报告。目前覆盖了系统管理模块的 5 个子模块。

**第二部分是手工功能测试。** 我根据 PRD 和 UI 设计稿编写手工测试用例，覆盖正向、反向、边界、异常场景。最近完成了平台设置页前端布局调整的回归测试，设计了 33 条用例，发现了一个服务器同步的状态不一致缺陷。

**第三部分是缺陷跟踪。** 我使用禅道/飞书等工具提交缺陷，跟踪修复进度，并复测验证。

我个人比较重视底层原理和代码质量，工作之余会整理学习笔记，也在准备把项目上传到 GitHub 并接入 CI/CD。

希望有机会加入贵公司，在测试开发方向继续深耕。

